/**
 * The Pashto text of the public content: features, industries, FAQs and pricing.
 *
 * It adds a "ps" translation next to the Dari and English ones that the other seeders write,
 * so it runs after them. Safe to run again. Features and industries are matched by slug;
 * FAQs, plans and add-ons by their Dari text, which the other seeders keep stable.
 */
class PashtoContentSeeder extends Seeder
{
    public function run(): void
    {
        $this->features();
        $this->industries();
        $this->faqs();
        $this->pricing();
        $this->posts();
    }

    private function features(): void
    {
        foreach ($this->featureText() as $slug => $row) {
            $feature = Feature::where('slug', $slug)->first();

            if (! $feature) {
                continue;
            }

            $feature->setTranslation('title', 'ps', $row['title']);
            $feature->setTranslation('summary', 'ps', $row['summary']);
            $feature->setTranslation('points', 'ps', $row['points']);
            $feature->setTranslation('overview', 'ps', $row['overview']);
            $feature->setTranslation('highlights', 'ps', array_map(fn (array $h) => ['title' => $h[0], 'text' => $h[1]], $row['highlights'] ?? []));
            $feature->setTranslation('steps', 'ps', $row['steps'] ?? []);
            $feature->save();
        }
    }

    private function industries(): void
    {
        foreach ($this->industryText() as $slug => $row) {
            $industry = Industry::where('slug', $slug)->first();

            if (! $industry) {
                continue;
            }

            $industry->setTranslation('title', 'ps', $row['title']);
            $industry->setTranslation('summary', 'ps', $row['summary']);
            $industry->setTranslation('points', 'ps', $row['points']);
            $industry->setTranslation('overview', 'ps', $row['overview']);
            $industry->setTranslation('highlights', 'ps', array_map(fn (array $h) => ['title' => $h[0], 'text' => $h[1]], $row['highlights'] ?? []));
            $industry->setTranslation('steps', 'ps', $row['steps'] ?? []);
            $industry->save();
        }
    }

    private function faqs(): void
    {
        foreach ($this->faqText() as $dari => [$question, $answer]) {
            $faq = Faq::all()->first(fn (Faq $f) => $f->getTranslation('question', 'fa', false) === $dari);

            if (! $faq) {
                continue;
            }

            $faq->setTranslation('question', 'ps', $question);
            $faq->setTranslation('answer', 'ps', $answer);
            $faq->save();
        }
    }

    private function pricing(): void
    {
        foreach ($this->planText() as $dari => $row) {
            $plan = PricingPlan::all()->first(fn (PricingPlan $p) => $p->getTranslation('name', 'fa', false) === $dari);

            if (! $plan) {
                continue;
            }

            foreach (['name', 'audience', 'includes', 'points'] as $field) {
                $plan->setTranslation($field, 'ps', $row[$field]);
            }
            $plan->save();
        }

        foreach ($this->addonText() as $dari => [$name, $description, $price]) {
            $addon = PricingAddon::all()->first(fn (PricingAddon $a) => $a->getTranslation('name', 'fa', false) === $dari);

            if (! $addon) {
                continue;
            }

            $addon->setTranslation('name', 'ps', $name);
            $addon->setTranslation('description', 'ps', $description);
            $addon->setTranslation('price_label', 'ps', $price);
            $addon->save();
        }
    }

    /** The first three articles, written by PostSeeder in Dari and English. The later twenty carry their own Pashto. */
    private function posts(): void
    {
        foreach ($this->postText() as $slug => $row) {
            $post = Post::where('slug', $slug)->first();

            if (! $post) {
                continue;
            }

            foreach (['title', 'excerpt', 'content'] as $field) {
                $post->setTranslation($field, 'ps', $row[$field]);
            }
            $post->save();
        }
    }

